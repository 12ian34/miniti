#!/usr/bin/env python3
"""Check/import immutable v1 wire fixtures; no sibling checkout is assumed.

Apple owns test-contracts/v1. Consumers keep SHA-256 pins and either pass
--source to a local canonical directory or use --fetch in CI. Bump the
contract directory/version when changing bytes rather than silently repinning.
"""
from pathlib import Path
import argparse
import hashlib
import json
import urllib.request

parser = argparse.ArgumentParser()
parser.add_argument('--source', type=Path)
parser.add_argument('--fetch', action='store_true')
parser.add_argument('--import-fixtures', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
apple = (root / 'MinitiTests').exists()
manifest_path = root / ('test-contracts/v1/manifest.json' if apple else 'test/fixtures/contract-manifest.json')
manifest = json.loads(manifest_path.read_text())
fixtures = {}
for name, digest in manifest['sha256'].items():
    destination = root / ('test-contracts/v1/' + name if apple else 'test/fixtures/' + ('sync-documents/' if name == 'meeting-v1.json' else '') + name)
    data = (args.source / name).read_bytes() if args.source else urllib.request.urlopen(manifest['canonical'] + name, timeout=30).read() if args.fetch else destination.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise SystemExit(f'{name}: canonical bytes differ from versioned SHA-256 pin')
    if args.import_fixtures:
        destination.write_bytes(data)
    elif destination.read_bytes() != data:
        raise SystemExit(f'{destination}: divergent fixture; run --import-fixtures from the canonical source')
    fixtures[name] = data.decode()

if apple:
    generated = '// Generated by scripts/check-test-contracts.py. Edit the versioned canonical fixtures.\nimport Foundation\n\nenum ContractFixtures {\n'
    for name, key in [('meeting-v1.json', 'meeting'), ('client-auth-vectors.json', 'auth'), ('reporting-v1.json', 'reporting'), ('recovery-v1.json', 'recovery'), ('review-370-v1.json', 'review370')]:
        generated += f'    static let {key} = #"""\n{fixtures[name].rstrip()}\n"""#\n'
    generated += '}\n'
    target = root / 'MinitiTests/ContractFixtures.swift'
    if args.import_fixtures:
        target.write_text(generated)
    elif not target.exists() or target.read_text() != generated:
        raise SystemExit('Swift fixture copy diverged; run scripts/check-test-contracts.py --import-fixtures')
print(f'contract v{manifest["version"]}: canonical hashes and local copies match')
